import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

// Owner-provided artwork only. Preserve PNG bytes, names and dimensions.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
assert(source, 'Pass the owner-supplied OG IMAGES directory.');
const cards = [
  ['home', 'home', 'Savo Technologies — websites, mobile apps and AI'],
  ['about', 'who-we-are', 'Savo Technologies — who we are'],
  ['ai', 'ai', 'Savo Technologies — AI solutions'],
  ['careers', 'careers', 'Savo Technologies — careers'],
  ['caseStudies', 'case-studies', 'Savo Technologies — case studies'],
  ['contact', 'contact', 'Savo Technologies — contact us'],
  ['enterprise', 'enterprise', 'Savo Technologies — enterprise solutions'],
  ['hire', 'hire-resources', 'Savo Technologies — hire dedicated resources'],
  ['industries', 'industries', 'Savo Technologies — industries'],
  ['insights', 'insights', 'Savo Technologies — insights'],
  ['meeting', 'meetings', 'Savo Technologies — book a meeting'],
  ['mobile', 'mobile-app-development', 'Savo Technologies — mobile app development'],
  ['design', 'product-design', 'Savo Technologies — product and UX design'],
  ['services', 'services', 'Savo Technologies — services'],
  ['start', 'start-a-project', 'Savo Technologies — start a project'],
  ['web', 'web-development', 'Savo Technologies — web development'],
  ['employeePortal', 'employee-portal', 'Savo Technologies — employee portal workspace', 'Employee portal workspace.png'],
  ['clientPortal', 'client-portal', 'Savo Technologies — client portal dashboard', 'Client portal dashboard.png'],
];
const imported = [];
for (const [key, slug, alt, originalName] of cards) {
  const file = `savo-og-${slug}.png`, sourceFile = originalName ?? file;
  const bytes = readFileSync(resolve(source, sourceFile));
  const metadata = await sharp(bytes).metadata();
  assert(metadata.format === 'png' && metadata.width >= 1200 && metadata.height >= 630, `${file}: PNG dimensions are too small.`);
  assert(metadata.width / metadata.height > 1.8 && metadata.width / metadata.height < 2, `${file}: unexpected social-preview aspect ratio.`);
  assert(bytes.length < 5 * 1024 * 1024, `${file}: exceeds the 5 MiB social-card limit.`);
  imported.push({ key, file, sourceFile, bytes, width: metadata.width, height: metadata.height, alt, sha256: createHash('sha256').update(bytes).digest('hex') });
}
const destination = resolve(root, 'public/images/og');
mkdirSync(destination, { recursive: true });
const registry = {};
for (const { key, file, sourceFile, bytes, width, height, alt, sha256 } of imported) {
  writeFileSync(resolve(destination, file), bytes);
  writeFileSync(resolve(destination, `${file}.json`), JSON.stringify({ provenance: 'owner-supplied', sourceFile, use: 'Open Graph and Twitter/X link previews', transformations: 'None; original PNG bytes preserved.', sha256, width, height, alt, rights: 'Supplied by the site owner for this website; no independent rights certification.' }, null, 2) + '\n');
  registry[key] = { file, width, height, alt, sha256 };
}
writeFileSync(resolve(root, 'src/constants/social-images.ts'), '// Generated by scripts/import-social-images.mjs from owner-supplied PNGs.\n// Re-import artwork to update dimensions and content-versioned metadata URLs.\nexport const SOCIAL_IMAGES = ' + JSON.stringify(registry, null, 2) + ' as const;\n\nexport type SocialImageKey = keyof typeof SOCIAL_IMAGES;\n');
console.log(`Imported ${imported.length} original PNGs, provenance sidecars and the typed social-image registry.`);
